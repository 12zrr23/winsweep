use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;
use serde::{Deserialize, Serialize};
use walkdir::WalkDir;
use crate::core::safety::SafetyGuard;

#[derive(Debug, Serialize, Deserialize, Clone)]
pub struct CleanItem {
    pub path: PathBuf,
    pub size: u64,
}

#[derive(Debug, Serialize, Deserialize, Clone)]
pub struct CleanCategory {
    pub id: String,
    pub name: String,
    pub description: String,
    pub requires_admin: bool,
    pub items: Vec<CleanItem>,
    pub total_size: u64,
    pub total_count: usize,
}

#[derive(Debug, Serialize, Deserialize, Clone)]
pub struct CleanCategorySummary {
    pub id: String,
    pub name: String,
    pub description: String,
    pub requires_admin: bool,
    pub total_size: u64,
    pub total_count: usize,
}

pub struct SystemCleaner {
    guard: SafetyGuard,
}

impl SystemCleaner {
    pub fn new() -> Self {
        Self {
            guard: SafetyGuard::new(),
        }
    }

    /// 扫描所有可清理的系统与用户缓存目录
    pub fn scan_all(&self) -> Vec<CleanCategory> {
        let mut categories = Vec::new();

        // 1. 用户临时目录 (%LOCALAPPDATA%\Temp)
        if let Ok(local_app) = std::env::var("LOCALAPPDATA") {
            let user_temp = PathBuf::from(&local_app).join("Temp");
            categories.push(self.scan_directory(
                "user_temp",
                "User Temp Files",
                "Temporary cache files generated by running applications",
                &user_temp,
                false,
            ));
        }

        // 2. 系统临时目录 (C:\Windows\Temp)
        if let Ok(windir) = std::env::var("WINDIR") {
            let sys_temp = PathBuf::from(&windir).join("Temp");
            categories.push(self.scan_directory(
                "sys_temp",
                "System Temp Files",
                "System-wide temporary runtime files (Requires Admin)",
                &sys_temp,
                true,
            ));

            // 3. Windows 更新下载缓存
            let update_cache = PathBuf::from(&windir).join("SoftwareDistribution").join("Download");
            categories.push(self.scan_directory(
                "windows_update",
                "Windows Update Cache",
                "Downloaded Windows Update installation packages (Requires Admin)",
                &update_cache,
                true,
            ));
        }

        // 4. 浏览器缓存 (Edge & Chrome)
        if let Ok(local_app) = std::env::var("LOCALAPPDATA") {
            let edge_cache = PathBuf::from(&local_app)
                .join("Microsoft")
                .join("Edge")
                .join("User Data")
                .join("Default")
                .join("Cache")
                .join("Cache_Data");
            if edge_cache.exists() {
                categories.push(self.scan_directory(
                    "edge_cache",
                    "Microsoft Edge Cache",
                    "Cached web assets and media files from Edge",
                    &edge_cache,
                    false,
                ));
            }

            let chrome_cache = PathBuf::from(&local_app)
                .join("Google")
                .join("Chrome")
                .join("User Data")
                .join("Default")
                .join("Cache")
                .join("Cache_Data");
            if chrome_cache.exists() {
                categories.push(self.scan_directory(
                    "chrome_cache",
                    "Google Chrome Cache",
                    "Web browser cache from Google Chrome",
                    &chrome_cache,
                    false,
                ));
            }

            // 5. 资源管理器缩略图缓存
            let explorer_dir = PathBuf::from(&local_app).join("Microsoft").join("Windows").join("Explorer");
            if explorer_dir.exists() {
                categories.push(self.scan_thumbnail_cache(&explorer_dir));
            }
        }

        categories
    }

    fn scan_directory(
        &self,
        id: &str,
        name: &str,
        description: &str,
        dir: &Path,
        requires_admin: bool,
    ) -> CleanCategory {
        let mut items = Vec::new();
        let mut total_size = 0u64;

        if dir.exists() && dir.is_dir() {
            for entry in WalkDir::new(dir).min_depth(1).max_depth(4).into_iter().filter_map(|e| e.ok()) {
                let p = entry.path();
                // 校验安全性：绝不触碰被安全策略保护的路径
                if self.guard.is_safe_to_delete(p).is_ok() {
                    if let Ok(meta) = fs::metadata(p) {
                        if meta.is_file() {
                            let size = meta.len();
                            total_size += size;
                            items.push(CleanItem {
                                path: p.to_path_buf(),
                                size,
                            });
                        }
                    }
                }
            }
        }

        let total_count = items.len();
        CleanCategory {
            id: id.to_string(),
            name: name.to_string(),
            description: description.to_string(),
            requires_admin,
            items,
            total_size,
            total_count,
        }
    }

    fn scan_thumbnail_cache(&self, explorer_dir: &Path) -> CleanCategory {
        let mut items = Vec::new();
        let mut total_size = 0u64;

        if let Ok(entries) = fs::read_dir(explorer_dir) {
            for entry in entries.flatten() {
                let path = entry.path();
                if let Some(file_name) = path.file_name().and_then(|s| s.to_str()) {
                    if file_name.starts_with("thumbcache_") && file_name.ends_with(".db") {
                        if self.guard.is_safe_to_delete(&path).is_ok() {
                            if let Ok(meta) = fs::metadata(&path) {
                                let size = meta.len();
                                total_size += size;
                                items.push(CleanItem {
                                    path: path.clone(),
                                    size,
                                });
                            }
                        }
                    }
                }
            }
        }

        let total_count = items.len();
        CleanCategory {
            id: "thumbnails".to_string(),
            name: "Explorer Thumbnail Cache".to_string(),
            description: "Windows Explorer image and folder thumbnail database files".to_string(),
            requires_admin: false,
            items,
            total_size,
            total_count,
        }
    }

    pub fn scan_summaries(&self) -> Vec<CleanCategorySummary> {
        self.scan_all()
            .into_iter()
            .map(|c| CleanCategorySummary {
                id: c.id,
                name: c.name,
                description: c.description,
                requires_admin: c.requires_admin,
                total_size: c.total_size,
                total_count: c.total_count,
            })
            .collect()
    }

    /// 执行清理操作：支持按选中的分类过滤
    pub fn clean_selected(&self, category_ids: &[String], dry_run: bool) -> (u64, usize) {
        let categories = self.scan_all();
        let mut freed_bytes = 0u64;
        let mut freed_files = 0usize;

        let filtered_categories: Vec<_> = categories
            .into_iter()
            .filter(|c| category_ids.is_empty() || category_ids.iter().any(|id| id == &c.id))
            .collect();

        if dry_run {
            for cat in filtered_categories {
                freed_bytes += cat.total_size;
                freed_files += cat.total_count;
            }
            return (freed_bytes, freed_files);
        }

        // 快速清理：临时缓存直接删除；被运行中程序占用的文件跳过（这是正常现象，不做回收站重试以免拖慢）
        let mut skipped = 0usize;
        for cat in filtered_categories {
            for item in cat.items {
                if self.guard.is_safe_to_delete(&item.path).is_err() {
                    continue;
                }
                crate::core::installer::clear_readonly(&item.path);
                match fs::remove_file(&item.path) {
                    Ok(_) => {
                        freed_bytes += item.size;
                        freed_files += 1;
                        self.guard.log_operation("CLEAN_FILE", &item.path, item.size);
                    }
                    Err(_) => skipped += 1,
                }
            }
        }
        if skipped > 0 {
            self.guard.log_operation("CLEAN_SKIPPED_LOCKED", std::path::Path::new(&format!("{} files", skipped)), 0);
        }

        (freed_bytes, freed_files)
    }

    /// 执行全量清理
    pub fn clean_all(&self, dry_run: bool) -> (u64, usize) {
        self.clean_selected(&[], dry_run)
    }

    /// 以管理员身份 (UAC 提权) 清理系统级临时目录
    pub fn clean_as_admin(&self) -> bool {
        let script = r#"
            $targetDirs = @(
                "$env:WINDIR\Temp",
                "$env:WINDIR\SoftwareDistribution\Download"
            )
            foreach ($d in $targetDirs) {
                if (Test-Path $d) {
                    Get-ChildItem -Path $d -File -Recurse -ErrorAction SilentlyContinue | ForEach-Object {
                        try { [System.IO.File]::Delete($_.FullName) } catch {}
                    }
                }
            }
        "#;

        let encoded = Self::encode_powershell_script(script);
        let status = Command::new("powershell")
            .arg("-NoProfile")
            .arg("-Command")
            .arg(format!("Start-Process powershell -Verb RunAs -ArgumentList '-NoProfile', '-EncodedCommand', '{}' -Wait", encoded))
            .status();

        status.map(|s| s.success()).unwrap_or(false)
    }

    /// 将脚本转为 PowerShell -EncodedCommand 所需的 UTF-16LE Base64 编码
    pub fn encode_powershell_script(script: &str) -> String {
        let utf16_bytes: Vec<u8> = script.encode_utf16().flat_map(|u| u.to_le_bytes()).collect();
        const CHARS: &[u8] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
        let mut result = String::new();
        let mut i = 0;
        while i < utf16_bytes.len() {
            let b0 = utf16_bytes[i];
            let b1 = if i + 1 < utf16_bytes.len() { utf16_bytes[i + 1] } else { 0 };
            let b2 = if i + 2 < utf16_bytes.len() { utf16_bytes[i + 2] } else { 0 };

            let n = ((b0 as u32) << 16) | ((b1 as u32) << 8) | (b2 as u32);

            result.push(CHARS[((n >> 18) & 63) as usize] as char);
            result.push(CHARS[((n >> 12) & 63) as usize] as char);

            if i + 1 < utf16_bytes.len() {
                result.push(CHARS[((n >> 6) & 63) as usize] as char);
            } else {
                result.push('=');
            }

            if i + 2 < utf16_bytes.len() {
                result.push(CHARS[(n & 63) as usize] as char);
            } else {
                result.push('=');
            }

            i += 3;
        }
        result
    }
}
